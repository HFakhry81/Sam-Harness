/**
 * Task file writer — renders Task Spec (source of truth) into task.ts / task.md.
 */
import * as fs from "fs";
import * as path from "path";
import {
  buildTaskSpec,
  needsClarify,
  renderSpecMarkdown,
  writeTaskSpecFiles,
  type ComposeAnswers,
  type SpecBuildInput,
  type TaskSpec,
} from "./taskSpec.js";

export type UiRoute = "architecture" | "operational" | "implement";

export type TaskDraftInput = SpecBuildInput & {
  /** If true (default when saving run), refuse to write when clarification needed */
  requireReady?: boolean;
};

export type TaskDraft = {
  id: string;
  route: UiRoute;
  title: string;
  targetRepo: string;
  packDir: string;
  body: string;
  allowClientCodeEdits: boolean;
  spec: TaskSpec;
  needsClarification: string[];
  confidence: number;
  ready: boolean;
};

export { detectRoute } from "./taskSpec.js";

export function buildTaskDraft(input: TaskDraftInput): TaskDraft {
  const spec = buildTaskSpec(input);
  const clarify = needsClarify(spec);
  return {
    id: spec.id,
    route: spec.route,
    title: spec.title,
    targetRepo: spec.targetRepo,
    packDir: spec.packDir,
    body: renderSpecMarkdown(spec),
    allowClientCodeEdits: spec.allowClientCodeEdits,
    spec,
    needsClarification: spec.needsClarification,
    confidence: spec.confidence,
    ready: !clarify,
  };
}

function escTemplate(s: string): string {
  return s.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

export function renderTaskTs(draft: TaskDraft): string {
  return `/**
 * Generated by Sam-Harness Task Spec Engine — edit via Control Plane UI.
 * id: ${draft.id}
 * intent: ${draft.spec.intent} · confidence: ${draft.confidence.toFixed(2)}
 * Source of truth: task.spec.json
 */
export type SamHarnessRoute = "operational" | "architecture" | "implement";

export type SamHarnessTask = {
  id: string;
  route: SamHarnessRoute;
  title: string;
  targetRepo: string;
  packDir: string;
  body: string;
};

export const taskConfig: SamHarnessTask = {
  id: ${JSON.stringify(draft.id)},
  route: ${JSON.stringify(draft.route)},
  title: ${JSON.stringify(draft.title)},
  targetRepo: ${JSON.stringify(draft.targetRepo)},
  packDir: ${JSON.stringify(draft.packDir)},
  body: \`
${escTemplate(draft.body)}
\`.trim(),
};

export function getTaskMarkdown(): string {
  return taskConfig.body;
}

export default taskConfig;
`;
}

export function writeTaskFiles(
  cwd: string,
  draft: TaskDraft
): { taskTs: string; taskMd: string; specJson: string } {
  if (!draft.ready) {
    throw new Error(
      `Task غير جاهز (confidence=${draft.confidence.toFixed(2)}). أجب على أسئلة التوضيح أولاً: ` +
        draft.needsClarification.join(" | ")
    );
  }
  const taskTs = path.join(cwd, "task.ts");
  const bak = path.join(cwd, "task.ts.bak");
  if (fs.existsSync(taskTs)) fs.copyFileSync(taskTs, bak);
  const { specJson, taskMd } = writeTaskSpecFiles(cwd, draft.spec);
  fs.writeFileSync(taskTs, renderTaskTs(draft), "utf-8");
  // Keep recoverable draft so UI can restore after refresh (cleared only on success idle)
  persistComposeDraft(cwd, draft, draft.spec.rawPrompt || draft.spec.goal || "");
  return { taskTs, taskMd, specJson };
}

/**
 * Always persist in-progress compose so the UI can restore after refresh / accidental clear.
 * Does NOT overwrite a ready task.ts until ready=true save.
 */
export function persistComposeDraft(cwd: string, draft: TaskDraft, prompt: string): string {
  const p = path.join(cwd, "task.draft.json");
  fs.writeFileSync(
    p,
    JSON.stringify(
      {
        savedAt: new Date().toISOString(),
        prompt,
        title: draft.title,
        ready: draft.ready,
        confidence: draft.confidence,
        needsClarification: draft.needsClarification,
        spec: draft.spec,
        body: draft.body,
      },
      null,
      2
    ),
    "utf-8"
  );
  // Keep a human-visible preview of the pending goal
  fs.writeFileSync(
    path.join(cwd, "task.pending.md"),
    `# Pending Task (not executed yet)\n\n## Prompt\n${prompt}\n\n## Ready\n${draft.ready}\n\n## Clarifications\n${
      draft.needsClarification.map((q) => `- ${q}`).join("\n") || "- none"
    }\n\n---\n\n${draft.body}\n`,
    "utf-8"
  );
  return p;
}

export function readComposeDraft(cwd: string): {
  prompt: string;
  title?: string;
  ready: boolean;
  confidence: number;
  needsClarification: string[];
  spec?: TaskDraft["spec"];
  body?: string;
} | null {
  const p = path.join(cwd, "task.draft.json");
  try {
    if (!fs.existsSync(p)) return null;
    return JSON.parse(fs.readFileSync(p, "utf-8"));
  } catch {
    return null;
  }
}

export function readCurrentTaskMeta(cwd: string): {
  exists: boolean;
  preview?: string;
  raw?: string;
} {
  const taskMd = path.join(cwd, "task.md");
  const taskTs = path.join(cwd, "task.ts");
  if (fs.existsSync(taskMd)) {
    const raw = fs.readFileSync(taskMd, "utf-8");
    return { exists: true, preview: raw.slice(0, 2000), raw };
  }
  if (fs.existsSync(taskTs)) {
    const raw = fs.readFileSync(taskTs, "utf-8");
    return { exists: true, preview: raw.slice(0, 2000), raw };
  }
  return { exists: false };
}

