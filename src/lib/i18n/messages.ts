export const CATALOGS: Record<AppLocale, MessageCatalog> = {
  ar: AR_MESSAGES,
  en: EN_MESSAGES,
};

export function catalogKeys(locale: AppLocale = "ar"): string[] {
  return Object.keys(CATALOGS[locale]).sort();
}

/** Keys present in `ar` but missing in `en`, and vice versa. */
export function missingTranslationKeys(): { missingInEn: string[]; missingInAr: string[] } {
  const arKeys = new Set(Object.keys(AR_MESSAGES));
  const enKeys = new Set(Object.keys(EN_MESSAGES));
  const missingInEn = [...arKeys].filter((k) => !enKeys.has(k)).sort();
  const missingInAr = [...enKeys].filter((k) => !arKeys.has(k)).sort();
  return { missingInEn, missingInAr };
}
